"""A chat's export as HTML pages that open offline, streamed as one ZIP.

The layout follows Telegram Desktop's own HTML export, so the archive's
importer (``telegram_import._parse_html_export``) reads it back:
``messages.html``, ``messages2.html`` and on, ``css/style.css`` and the media
in tdesktop's folder names, all under one top folder. ``index.html`` is
written last and says what the export holds and what it left out.

Everything here is stdlib. Every text and attribute goes through
``html.escape``, and every name inside the ZIP is generated by this module:
a stored file name only ever appears as escaped text and in the ``download``
attribute. The pages carry no script, no font and no remote resource.

Memory stays bounded however long the chat: one page of HTML (at most
``MAX_MESSAGES_PER_PAGE`` messages), one ``CHUNK`` of a file, zipfile's own
record per entry (about 0.5 KB in memory and 80 bytes or so of central
directory each, which the last piece of the stream carries), a map of the
files already written (for files shared through ``_shared``), each page's
first message id and the id of every exported message (8 bytes each, so a
reply knows whether its target is in the export).

``spool_messages`` reads the whole database walk into a temporary file
before the first byte goes out, so the read snapshot closes in the time the
database takes, never in the time a slow client takes to download.
"""


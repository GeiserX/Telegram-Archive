def parse_media_kinds(value: str | None) -> frozenset[str]:
    """The media kinds a ``media=`` parameter names, or ValueError naming the first unknown one.

    None or an empty value is no media: a text-only export.
    """
    if value is None:
        return frozenset()
    kinds = set()
    for item in value.split(","):
        name = item.strip()
        if not name:
            continue
        if name not in MEDIA_KINDS:
            raise ValueError(f"Unknown media type '{name}'. Use any of: {', '.join(MEDIA_KINDS)}")
        kinds.add(name)
    return frozenset(kinds)


def _esc(value: object) -> str:
    return html.escape("" if value is None else str(value), quote=True)


def safe_href(url: str, *, schemes: frozenset[str]) -> str | None:
    """``url`` when it starts with one of ``schemes`` and ``://``, else None.

    The same rule as the viewer's ``safeEntityUrl``: anchored at the first
    character, so a leading control character, a protocol-relative ``//`` or
    ``javascript:`` in any case never becomes a link.
    """
    if not isinstance(url, str):
        return None
    match = re.match(r"^([A-Za-z][A-Za-z0-9+.-]*)://", url)
    if not match or match.group(1).lower() not in schemes:
        return None
    return url


def _link(url: str, inner: str) -> str:
    return f'<a href="{_esc(url)}" target="_blank" rel="noopener noreferrer">{inner}</a>'


def _linkify(text: str) -> str:
    """Escaped ``text`` with its http and https URLs as links (the viewer's ``linkifyText``, without tags)."""
    parts = _URL_SPLIT_RE.split(text)
    return "".join(_esc(part) if index % 2 == 0 else _link(part, _esc(part)) for index, part in enumerate(parts))


class _Utf16:
    """A string indexed in UTF-16 code units, the units Telegram's entity offsets count."""

    def __init__(self, text: str) -> None:
        self._units = text.encode("utf-16-le", "surrogatepass")
        self.length = len(self._units) // 2

    def _align(self, index: int) -> int:
        """``index`` moved back off the second half of a surrogate pair, so a pair is never split."""
        if 0 < index < self.length:
            unit = int.from_bytes(self._units[index * 2 : index * 2 + 2], "little")
            before = int.from_bytes(self._units[index * 2 - 2 : index * 2], "little")
            if 0xDC00 <= unit <= 0xDFFF and 0xD800 <= before <= 0xDBFF:
                return index - 1
        return index

    def slice(self, start: int, end: int) -> str:
        start, end = self._align(start), self._align(end)
        return self._units[start * 2 : end * 2].decode("utf-16-le", "replace")


def _is_int(value: object) -> bool:
    return isinstance(value, int) and not isinstance(value, bool)


def _wrap_entity(node: dict, inner: str, text: _Utf16) -> str:
    kind = node["type"]
    if kind is None:
        return inner
    if kind == "bold":
        return f"<strong>{inner}</strong>"
    if kind == "italic":
        return f"<em>{inner}</em>"
    if kind == "underline":
        return f"<u>{inner}</u>"
    if kind == "strikethrough":
        return f"<s>{inner}</s>"
    if kind == "code":
        return f'<code class="tg-code">{inner}</code>'
    if kind == "pre":
        return f'<pre class="tg-pre"><code>{inner}</code></pre>'
    if kind == "blockquote":
        return f'<blockquote class="tg-blockquote">{inner}</blockquote>'
    if kind == "spoiler":
        return f'<span class="tg-spoiler" tabindex="0">{inner}</span>'
    if kind == "text_url":
        url = safe_href(node.get("url"), schemes=_TEXT_URL_SCHEMES)
        return _link(url, inner) if url else inner
    if kind == "url":
        raw = text.slice(node["offset"], node["end"])
        return _link(raw, inner) if _HTTP_RE.match(raw) else inner
    if kind == "email":
        raw = text.slice(node["offset"], node["end"])
        return f'<a href="mailto:{_esc(raw)}">{inner}</a>' if _EMAIL_RE.match(raw) else inner
    if kind in ("mention", "mention_name"):
        return f'<span class="tg-mention">{inner}</span>'
    # custom_emoji keeps its fallback character; any other kind its text.
    return inner


def _render_entities(raw_text: str, entities: list) -> str:
    """A port of the viewer's ``renderEntityHtml``: escape-first, nested, offsets in UTF-16 units."""
    text = _Utf16(raw_text)
    length = text.length
    valid = []
    for entity in entities:
        if not isinstance(entity, dict):
            continue
        offset, size = entity.get("offset"), entity.get("length")
        if not (_is_int(offset) and _is_int(size) and offset >= 0 and size > 0 and offset < length):
            continue
        valid.append(
            {
                "type": entity.get("type"),
                "url": entity.get("url"),
                "offset": offset,
                "end": min(offset + size, length),
                "children": [],
            }
        )
    valid.sort(key=lambda node: (node["offset"], -node["end"]))
    root = {"type": None, "offset": 0, "end": length, "children": []}
    stack = [root]
    for node in valid:
        while node["offset"] >= stack[-1]["end"] and len(stack) > 1:
            stack.pop()
        parent = stack[-1]
        if node["end"] > parent["end"]:
            node["end"] = parent["end"]
        if node["end"] <= node["offset"]:
            continue
        parent["children"].append(node)
        stack.append(node)

    def leaf(start: int, end: int, escape_only: bool) -> str:
        piece = text.slice(start, end)
        return _esc(piece) if escape_only else _linkify(piece)

    def render(node: dict, escape_only: bool) -> str:
        escape_here = escape_only or node["type"] in _ESCAPE_ONLY_ENTITY_TYPES
        inner = []
        cursor = node["offset"]
        for child in node["children"]:
            if child["offset"] > cursor:
                inner.append(leaf(cursor, child["offset"], escape_here))
            inner.append(render(child, escape_here))
            cursor = child["end"]
        if cursor < node["end"]:
            inner.append(leaf(cursor, node["end"], escape_here))
        return _wrap_entity(node, "".join(inner), text)

    return render(root, False)


def render_text(text: str | None, entities: list[dict] | None) -> str:
    """A message text as HTML: its formatting entities, else linkified plain text.

    A malformed entity list degrades to the plain text, as in the viewer.
    """
    raw = "" if text is None else str(text)
    if not isinstance(entities, list) or not entities:
        return _linkify(raw)
    try:
        return _render_entities(raw, entities)
    except Exception:
        return _linkify(raw)


def media_entry_name(folder: str, message_id: int, n: int, stored_name: str | None) -> str:
    """The ZIP entry name of a message's ``n``-th media: ``{folder}/{message_id}_{n}{ext}``.

    Only the extension comes from the stored name, and only when it is one
    to eight ASCII letters or digits, so no stored name can steer the entry
    out of its folder or past a file-name length limit. An extension a
    browser would open as a page (``.html``, ``.svg``...) is dropped, so a
    sender's file never runs as a local page when its link is clicked.
    """
    ext = ""
    if isinstance(stored_name, str):
        base = stored_name.replace("\\", "/").rsplit("/", 1)[-1]
        candidate = os.path.splitext(base)[1]
        if _SAFE_EXT_RE.match(candidate) and candidate.lower() not in _ACTIVE_EXTENSIONS:
            ext = candidate
    return f"{folder}/{int(message_id)}_{int(n)}{ext}"


def _page_file(page: int) -> str:
    return "messages.html" if page == 1 else f"messages{page}.html"


def _format_size(size: object) -> str:
    if not _is_int(size) or size < 0:
        return ""
    value = float(size)
    for unit in ("B", "KB", "MB", "GB"):
        if value < 1024 or unit == "GB":
            return f"{int(value)} B" if unit == "B" else f"{value:.1f} {unit}"
        value /= 1024
    return ""


def _format_duration(seconds: object) -> str:
    if not _is_int(seconds) or seconds < 0:
        return ""
    hours, rest = divmod(seconds, 3600)
    minutes, secs = divmod(rest, 60)
    return f"{hours}:{minutes:02d}:{secs:02d}" if hours else f"{minutes}:{secs:02d}"


def _parse_date(value: object) -> datetime | None:
    if isinstance(value, datetime):
        parsed = value
    elif isinstance(value, str) and value:
        try:
            parsed = datetime.fromisoformat(value)
        except ValueError:
            return None
    else:
        return None
    # The archive stores naive UTC.
    return parsed.replace(tzinfo=UTC) if parsed.tzinfo is None else parsed


def _date_title(when: datetime, tz: tzinfo) -> str:
    """``DD.MM.YYYY HH:MM:SS UTC+HH:MM``, the format the importer's ``parse_html_date`` reads."""
    local = when.astimezone(tz)
    offset = local.utcoffset()
    minutes = int(offset.total_seconds() // 60) if offset is not None else 0
    sign = "+" if minutes >= 0 else "-"
    minutes = abs(minutes)
    return f"{local:%d.%m.%Y %H:%M:%S} UTC{sign}{minutes // 60:02d}:{minutes % 60:02d}"


def _date_label(value: object, tz: tzinfo) -> str:
    when = _parse_date(value)
    return f"{when.astimezone(tz):%d.%m.%Y %H:%M}" if when else ""


def _day_label(when: datetime, tz: tzinfo) -> str:
    local = when.astimezone(tz)
    return f"{local.day} {local:%B %Y}"


def _initials(name: str) -> str:
    words = [word for word in name.split() if word]
    return "".join(word[0] for word in words[:2]).upper() or "?"


def _userpic_class(name: str) -> int:
    return sum(ord(char) for char in name) % 8 + 1


@dataclass
class _MediaPlan:
    """One media row of a message as the export draws it: included (with its entry) or skipped (with why)."""

    media: dict
    kind: str | None
    display_name: str
    entry: str | None = None
    skip: str | None = None
    size: int | None = None
    poster: str | None = None
    player: str | None = None  # "img", "video", "audio" or None (a link card only)
    source: Path | None = None
    duplicate: bool = False


@dataclass
class _PageContext:
    """What a message renders against: the options, the page list for replies, the zone for dates."""

    options: HtmlExportOptions
    tz: tzinfo
    page_first_ids: list[int] = field(default_factory=list)
    exported_ids: array = field(default_factory=lambda: array("q"))
    plans: dict[str, _MediaPlan] = field(default_factory=dict)

    def add_message(self, message_id: int) -> None:
        """Record an exported id. They arrive in order, so this is an append but for an odd archive."""
        if not self.exported_ids or message_id > self.exported_ids[-1]:
            self.exported_ids.append(message_id)
        else:
            insort(self.exported_ids, message_id)

    def reply_href(self, target: int) -> str | None:
        """The page and anchor of an exported message, or None when the export does not hold it."""
        index = bisect_left(self.exported_ids, target)
        if index == len(self.exported_ids) or self.exported_ids[index] != target:
            return None
        page = bisect_right(self.page_first_ids, target)
        if page < 1:
            return None
        return f"{_page_file(page)}#go_to_message{int(target)}"


def _player_for(kind: str | None, media: dict, players: bool) -> str | None:
    """The element an included file is drawn with, by its MIME family, as ``_inline_media_type`` picks it."""
    name = media.get("file_name") or media.get("file_path") or ""
    guessed = mimetypes.guess_type(str(name))[0] or media.get("mime_type") or ""
    if not isinstance(guessed, str) or guessed == "image/svg+xml":
        return None
    family = guessed.split("/", 1)[0]
    if kind in ("photo", "sticker", "gif") and family == "image":
        return "img"
    if not players:
        return None
    if kind in ("video", "video_note", "gif", "sticker") and family == "video":
        return "video"
    if kind in ("voice", "file") and family == "audio":
        return "audio"
    return None


def _skip_text(reason: str, options: HtmlExportOptions) -> str:
    return SKIP_REASONS[reason].format(mb=options.max_file_bytes // (1024 * 1024))


def _render_media(plan: _MediaPlan, ctx: _PageContext) -> str:
    media = plan.media
    media_type = media.get("type")
    css = _MEDIA_CLASS.get(media_type, "media_file")
    label = _TYPE_LABEL.get(media_type, "File")
    name = _esc(plan.display_name)
    duration = _format_duration(media.get("duration"))
    size = _format_size(plan.size if plan.size is not None else media.get("file_size"))
    href = _esc(quote(plan.entry)) if plan.entry else None

    if href and plan.player == "img" and media_type == "photo":
        return (
            f'<div class="media_wrap"><a class="photo_wrap" href="{href}">'
            f'<img class="photo" loading="lazy" src="{href}" alt="{_esc(label)}"></a></div>'
        )

    parts = [f'<div class="media_wrap"><div class="media {css}{"" if href else " skipped"}">']
    if href and plan.player == "img":
        parts.append(f'<img class="sticker" loading="lazy" src="{href}" alt="{_esc(label)}">')
    elif href and plan.player == "video":
        poster = f' poster="{_esc(quote(plan.poster))}"' if plan.poster else ""
        if media_type == "animation" or media_type == "sticker":
            attrs = ' loop muted playsinline controls preload="metadata"'
        elif media_type == "video_note":
            attrs = ' class="round" controls preload="none"'
        else:
            attrs = ' controls preload="none"'
        parts.append(f'<video{attrs}{poster} src="{href}"></video>')
    elif href and plan.player == "audio":
        parts.append(f'<audio controls preload="none" src="{href}"></audio>')

    animated = str(plan.display_name).lower().endswith(".tgs") or media.get("mime_type") == "application/x-tgsticker"
    title = "Animated sticker" if media_type == "sticker" and animated else label
    card = [f'<div class="title bold">{name or _esc(title)}</div>']
    if duration:
        card.append(f'<div class="description">{duration}</div>')
    status = [_esc(title)] if name else []
    if size:
        status.append(size)
    if plan.skip:
        status.append(_esc(_skip_text(plan.skip, ctx.options)))
    card.append(f'<div class="status details">{" · ".join(status)}</div>')
    if href:
        parts.append(f'<a class="media_link" href="{href}" download="{name}">{"".join(card)}</a>')
    else:
        parts.append(f'<div class="media_card">{"".join(card)}</div>')
    parts.append("</div></div>")
    return "".join(parts)


def _render_payload(kind: str, payload: Any, snapshots: list) -> str:
    if not isinstance(payload, dict):
        payload = {}
    if kind == "poll":
        results = payload.get("results")
        for snapshot in reversed(snapshots or []):
            if isinstance(snapshot, dict) and snapshot.get("kind") == "poll":
                later = (snapshot.get("payload") or {}).get("results")
                if isinstance(later, dict):
                    results = later
                break
        voters: dict[str, int] = {}
        total = None
        if isinstance(results, dict):
            total = results.get("total_voters")
            for entry in results.get("results") or []:
                if isinstance(entry, dict) and _is_int(entry.get("voters")):
                    voters[str(entry.get("option"))] = entry["voters"]
        rows = []
        for answer in payload.get("answers") or []:
            if not isinstance(answer, dict):
                continue
            count = voters.get(str(answer.get("option")))
            suffix = f' <span class="details">{count}</span>' if count is not None else ""
            rows.append(f"<li>{_esc(answer.get('text'))}{suffix}</li>")
        votes = f" · {int(total)} votes" if _is_int(total) else ""
        return (
            f'<div class="media_wrap"><div class="media_poll"><div class="question bold">'
            f'{_esc(payload.get("question"))}</div><div class="details">Poll{votes}</div>'
            f'<ul class="answers">{"".join(rows)}</ul></div></div>'
        )
    if kind in ("geo", "geo_live", "venue"):
        lat, lon = payload.get("lat"), payload.get("long")
        lines = []
        if kind == "venue":
            if payload.get("title"):
                lines.append(f'<div class="bold">{_esc(payload.get("title"))}</div>')
            if payload.get("address"):
                lines.append(f'<div class="details">{_esc(payload.get("address"))}</div>')
        label = "Live location" if kind == "geo_live" else "Location"
        if isinstance(lat, (int, float)) and isinstance(lon, (int, float)) and not isinstance(lat, bool):
            coords = f"{float(lat):.6f}, {float(lon):.6f}"
            url = f"https://www.openstreetmap.org/?mlat={float(lat):.6f}&mlon={float(lon):.6f}"
            lines.append(f'<div class="details">{label}: {_link(url, _esc(coords))}</div>')
        else:
            lines.append(f'<div class="details">{label} unavailable</div>')
        return f'<div class="media_wrap"><div class="media_location">{"".join(lines)}</div></div>'
    if kind == "contact":
        name = " ".join(str(payload.get(key) or "") for key in ("first_name", "last_name")).strip()
        phone = payload.get("phone_number") or ""
        return (
            f'<div class="media_wrap"><div class="media_contact"><div class="bold">{_esc(name or "Contact")}</div>'
            f'<div class="details">{_esc(phone)}</div></div></div>'
        )
    if kind == "dice":
        value = payload.get("value")
        text = f"{payload.get('emoticon') or 'Dice'} {value}" if _is_int(value) else "Dice"
        return f'<div class="media_wrap"><div class="media_other details">{_esc(text)}</div></div>'
    labels = {
        "invoice": "Invoice",
        "story": "Story",
        "giveaway": "Giveaway",
        "giveaway_results": "Giveaway results",
        "game": "Game",
        "unsupported": "A message this version of Telegram could not show",
    }
    text = labels.get(kind, kind)
    if kind in ("invoice", "game") and payload.get("title"):
        text = f"{text}: {payload.get('title')}"
    return f'<div class="media_wrap"><div class="media_other details">{_esc(text)}</div></div>'


def _render_webpage(webpage: Any) -> str:
    if not isinstance(webpage, dict):
        return ""
    url = safe_href(webpage.get("url"), schemes=_URL_SCHEMES)
    lines = []
    if webpage.get("site_name"):
        lines.append(f'<div class="site_name details">{_esc(webpage.get("site_name"))}</div>')
    if webpage.get("title"):
        lines.append(f'<div class="bold">{_esc(webpage.get("title"))}</div>')
    if webpage.get("description"):
        lines.append(f'<div class="description_text">{_esc(webpage.get("description"))}</div>')
    if url:
        lines.append(f'<div class="details">{_link(url, _esc(webpage.get("display_url") or url))}</div>')
    if not lines:
        return ""
    return f'<div class="webpage">{"".join(lines)}</div>'


def _render_reactions(reactions: Any) -> str:
    chips = []
    for reaction in reactions if isinstance(reactions, list) else []:
        if not isinstance(reaction, dict) or not _is_int(reaction.get("count")) or reaction["count"] <= 0:
            continue
        emoji = str(reaction.get("emoji") or "")
        shown = "★" if emoji.startswith("custom_") else emoji
        title = ' title="Custom emoji"' if emoji.startswith("custom_") else ""
        chips.append(f'<span class="reaction"{title}>{_esc(shown)} {reaction["count"]}</span>')
    return f'<div class="reactions">{"".join(chips)}</div>' if chips else ""


def _render_versions(versions: Any, tz: tzinfo) -> str:
    if not isinstance(versions, list) or not versions:
        return ""
    items = []
    for version in versions:
        if not isinstance(version, dict):
            continue
        body = []
        when = _date_label(version.get("date"), tz)
        body.append(f'<div class="version_date details">{_esc(when)}</div>')
        if version.get("text") is not None:
            body.append(f'<div class="version_text">{render_text(version.get("text"), version.get("entities"))}</div>')
        names = [
            media_display_filename(str(media.get("file_name")))
            for media in version.get("media") or []
            if isinstance(media, dict) and media.get("file_name")
        ]
        if names:
            body.append(f'<div class="version_media details">Media: {_esc(", ".join(names))}</div>')
        items.append(f'<div class="version">{"".join(body)}</div>')
    return f'<details class="versions"><summary>Earlier versions ({len(items)})</summary>{"".join(items)}</details>'


def _transcript_of(msg: dict, media_id: object) -> str | None:
    for row in msg.get("transcripts") or []:
        if isinstance(row, dict) and row.get("media_id") == media_id:
            text = row.get("text")
            if isinstance(text, str) and text.strip():
                return text
    return None


def render_message(msg: dict, ctx: _PageContext) -> str:
    """One message as tdesktop's ``div.message`` markup, readable by the archive's importer."""
    message_id = int(msg["id"])
    raw = msg.get("raw") if isinstance(msg.get("raw"), dict) else {}
    when = _parse_date(msg.get("date"))
    date_title = _esc(_date_title(when, ctx.tz)) if when else ""
    date_short = _esc(f"{when.astimezone(ctx.tz):%H:%M}") if when else ""

    if raw.get("service_type") == "service":
        # Rows captured before the wording was stored carry no text: name the action instead.
        wording = (msg.get("text") or "").strip()
        if not wording:
            action = raw.get("action_type")
            wording = str(action).replace("_", " ").capitalize() if action else "Service message"
        return (
            f'<div class="message service" id="message{message_id}"><a id="go_to_message{message_id}"></a>'
            f'<div class="body details" title="{date_title}"><span class="date" title="{date_title}"></span>'
            f"{_esc(wording)}</div></div>\n"
        )

    sender = (msg.get("sender") or {}).get("name") or "Unknown"
    classes = ["message", "default", "clearfix"]
    if msg.get("is_outgoing"):
        classes.append("outgoing")
    if msg.get("is_deleted"):
        classes.append("deleted")
    out = [
        f'<div class="{" ".join(classes)}" id="message{message_id}"><a id="go_to_message{message_id}"></a>',
        f'<div class="pull_left userpic_wrap"><div class="userpic userpic{_userpic_class(sender)}">'
        f"{_esc(_initials(sender))}</div></div>",
        '<div class="body">',
        f'<div class="pull_right date details" title="{date_title}">{date_short}</div>',
        f'<div class="from_name">{_esc(sender)}</div>',
    ]
    forward_name = raw.get("forward_from_name")
    if forward_name or raw.get("forward_origin"):
        out.append(
            '<div class="forwarded body"><div class="details">Forwarded from</div>'
            f'<div class="from_name">{_esc(forward_name or "another chat")}</div></div>'
        )
    reply_to = msg.get("reply_to")
    if _is_int(reply_to):
        href = ctx.reply_href(reply_to)
        quote_text = msg.get("reply_to_text")
        excerpt = f' <span class="reply_quote">{_esc(quote_text)}</span>' if quote_text else ""
        if href:
            out.append(
                f'<div class="reply_to details">In reply to <a href="{_esc(href)}">this message</a>{excerpt}</div>'
            )
        else:
            # Still a go_to_message link, so a re-import keeps the reply's id; the page has no such anchor.
            out.append(
                f'<div class="reply_to details">In reply to <a href="#go_to_message{int(reply_to)}">'
                f"a message outside this export</a>{excerpt}</div>"
            )

    for media in msg.get("media") or []:
        plan = ctx.plans.get(str(media.get("media_id"))) if isinstance(media, dict) else None
        if plan is None:
            continue
        out.append(_render_media(plan, ctx))
        transcript = _transcript_of(msg, media.get("media_id"))
        if transcript:
            out.append(f'<div class="transcript details">{_esc(transcript)}</div>')

    text = msg.get("text")
    if text:
        out.append(f'<div class="text">{render_text(text, raw.get("entities"))}</div>')
    for kind, payload in (msg.get("media_payload") or {}).items():
        out.append(_render_payload(kind, payload, msg.get("snapshots") or []))
    out.append(_render_webpage(raw.get("webpage")))
    out.append(_render_reactions(msg.get("reactions")))

    marks = []
    if raw.get("post_author"):
        marks.append(f'<span class="signature">{_esc(raw.get("post_author"))}</span>')
    if msg.get("is_pinned"):
        marks.append('<span class="pinned">Pinned</span>')
    edit_date = _parse_date(msg.get("edit_date"))
    if edit_date and msg.get("edit_hide") != 1:
        marks.append(f'<span class="edited" title="{_esc(_date_title(edit_date, ctx.tz))}">edited</span>')
    if marks:
        out.append(f'<div class="marks details">{" ".join(marks)}</div>')
    if msg.get("is_deleted"):
        deleted_at = _date_label(msg.get("deleted_at"), ctx.tz)
        note = f"Deleted from Telegram on {deleted_at}" if deleted_at else "Deleted from Telegram"
        out.append(f'<div class="deleted_note details">{_esc(note)}</div>')
    out.append(_render_versions(msg.get("versions"), ctx.tz))
    out.append("</div></div>\n")
    return "".join(out)


def _chat_title(chat: dict) -> str:
    return str(chat.get("title") or chat.get("username") or "Chat")


def render_page(chat: dict, body: str, page: int, has_next: bool) -> str:
    """One ``messages{N}.html``: the chat header, links to the neighbouring pages, then ``body``."""
    title = _esc(_chat_title(chat))
    nav = ['<a href="index.html">Index</a>']
    if page > 1:
        nav.append(f'<a href="{_page_file(page - 1)}">Previous page</a>')
    if has_next:
        nav.append(f'<a href="{_page_file(page + 1)}">Next page</a>')
    navigation = f'<div class="page_nav">{" ".join(nav)}</div>'
    return (
        _HEAD.format(title=title)
        + '<div class="page_wrap"><div class="page_header"><div class="content">'
        + f'<div class="text bold">{title}</div></div></div>\n'
        + navigation
        + '\n<div class="page_body chat_page"><div class="history">\n'
        + body
        + "</div></div>\n"
        + navigation
        + "\n</div>\n</body>\n</html>\n"
    )


def render_index(
    chat: dict,
    filters: dict | None,
    options: HtmlExportOptions,
    pages: list,
    skipped: Counter,
    *,
    exported_at: datetime | None = None,
    version: str = "",
    files: int = 0,
) -> str:
    """``index.html``: what the export holds, what it left out, and every page with its dates."""
    title = _esc(_chat_title(chat))
    lines = [f'<div class="page_header"><div class="content"><div class="text bold">{title}</div></div></div>']
    lines.append('<div class="page_body index">')
    when = (exported_at or datetime.now(UTC)).astimezone(UTC)
    lines.append(f"<p>Exported {when:%Y-%m-%d %H:%M:%S} UTC by Telegram-Archive {_esc(version)}.</p>")
    if filters:
        bits = [f"{_esc(key)}: {_esc(value)}" for key, value in filters.items() if value]
        lines.append(
            f'<p class="filters"><strong>Filtered export, not the full history.</strong> {"; ".join(bits)}</p>'
        )
    else:
        lines.append('<p class="filters">The whole history the archive holds.</p>')
    if options.media:
        kinds = ", ".join(kind for kind in MEDIA_KINDS if kind in options.media)
        lines.append(
            f"<p>Media included: {_esc(kinds)}. Files up to {options.max_file_bytes // (1024 * 1024)} MB. "
            f"{'Players inside the page' if options.players else 'Links to the files'}. "
            f"{files} file{'s' if files != 1 else ''} copied.</p>"
        )
    else:
        lines.append("<p>Media included: none (text only).</p>")
    if sum(skipped.values()):
        items = "".join(
            f"<li>{_esc(_skip_text(reason, options))}: {skipped[reason]}</li>"
            for reason in SKIP_REASONS
            if skipped.get(reason)
        )
        lines.append(f'<p>Media shown without its file:</p><ul class="skip_counts">{items}</ul>')
    if any(count for _number, _first, _last, count in pages):
        rows = []
        for number, first, last, count in pages:
            rows.append(
                f'<li><a href="{_page_file(number)}">Page {number}</a> '
                f'<span class="details">{_esc(first)} to {_esc(last)}, '
                f"{count} message{'s' if count != 1 else ''}</span></li>"
            )
        lines.append(f'<ol class="pages">{"".join(rows)}</ol>')
    else:
        lines.append('<p><a href="messages.html">messages.html</a>: no messages in this export.</p>')
    lines.append("</div>")
    return _HEAD.format(title=title) + '<div class="page_wrap">' + "\n".join(lines) + "</div>\n</body>\n</html>\n"


class _ZipSink:
    """The file object zipfile writes to: no seek and no tell, so zipfile writes data descriptors."""

    def __init__(self) -> None:
        self._parts: list[bytes] = []
        self.size = 0

    def write(self, data: bytes) -> int:
        if data:
            self._parts.append(bytes(data))
            self.size += len(data)
        return len(data)

    def flush(self) -> None:
        pass

    def take(self) -> bytes:
        data = b"".join(self._parts)
        self._parts.clear()
        self.size = 0
        return data


def _zip_info(name: str, compress: int, size: int) -> zipfile.ZipInfo:
    info = zipfile.ZipInfo(name, date_time=datetime.now(UTC).timetuple()[:6])
    info.compress_type = compress
    info.file_size = size
    # A regular file, rw-r--r--: no entry is ever a symlink.
    info.external_attr = 0o100644 << 16
    return info


async def _write_bytes(zf: zipfile.ZipFile, sink: _ZipSink, name: str, data: bytes, compress: int):
    """Write one in-memory entry, yielding what the sink holds whenever it reaches ``CHUNK``."""
    with zf.open(_zip_info(name, compress, len(data)), "w") as dest:
        for start in range(0, len(data), _PAGE_WRITE_SLICE):
            dest.write(data[start : start + _PAGE_WRITE_SLICE])
            if sink.size >= CHUNK:
                yield sink.take()
    if sink.size >= CHUNK:
        yield sink.take()


async def spool_messages(messages: AsyncIterator[dict]) -> AsyncIterator[dict]:
    """``messages`` read to the end into a temporary file first, then yielded back from it.

    The database walk holds one read snapshot (a transaction) open while it
    runs. Draining it before the ZIP starts closes that snapshot in the time
    the database takes, not in the hours a large export can take to reach a
    slow client. Memory stays bounded: lines go to disk in batches of about
    1 MiB and come back one batch at a time. Datetimes come back as ISO
    strings, which every date the renderer reads accepts.
    """
    spool = await asyncio.to_thread(tempfile.TemporaryFile, "w+b")
    try:
        batch: list[bytes] = []
        size = 0
        async for msg in messages:
            line = json.dumps(msg, ensure_ascii=False, default=_spool_default).encode("utf-8") + b"\n"
            batch.append(line)
            size += len(line)
            if size >= _SPOOL_BATCH:
                await asyncio.to_thread(spool.write, b"".join(batch))
                batch, size = [], 0
        if batch:
            await asyncio.to_thread(spool.write, b"".join(batch))
        await asyncio.to_thread(spool.seek, 0)
        while True:
            lines = await asyncio.to_thread(spool.readlines, _SPOOL_BATCH)
            if not lines:
                break
            for line in lines:
                yield json.loads(line)
    finally:
        spool.close()


def _spool_default(value: object) -> str:
    if isinstance(value, datetime):
        return value.isoformat()
    return str(value)


def safe_top_name(chat_name: str) -> str:
    """``chat_name`` kept to letters, digits, space, ``-`` and ``_``, and short enough for any filesystem."""
    safe = "".join(c for c in chat_name if c.isalnum() or c in (" ", "-", "_")).strip()
    encoded = safe.encode("utf-8")[:_TOP_NAME_MAX_BYTES]
    return encoded.decode("utf-8", "ignore").strip() or "chat"


async def iter_html_zip(
    messages: AsyncIterator[dict],
    *,
    chat: dict,
    filters: dict | None,
    options: HtmlExportOptions,
    resolve_media: Callable[[str], Path | None],
    poster: Callable[[dict, Path, bool], Awaitable[Path | None]] | None,
    tz: tzinfo,
    top: str,
    version: str = "",
) -> AsyncIterator[bytes]:
    """Stream the export as ZIP bytes, in pieces of about ``CHUNK``.

    ``messages`` is ``get_messages_for_export(..., render=True)``.
    ``resolve_media`` maps a media row's stored ``file_path`` to the real file
    inside the media root, or None (the caller's containment check).
    ``poster(media, source, may_generate)`` returns a still for an included
    video, or None; ``may_generate`` turns False once the export has spent
    ``POSTER_BUDGET_SECONDS`` on posters, and then only a cached still may be
    returned. ``top`` is the top folder every entry sits under.

    A file that cannot be opened is drawn as missing. A file that fails once
    its entry is open raises: the response ends with no central directory,
    so the ZIP fails to open instead of holding a quietly short file.
    """
    sink = _ZipSink()
    zf = zipfile.ZipFile(sink, "w", allowZip64=True)
    poster_of: dict[str, str] = {}
    poster_seconds = 0.0
    prefix = f"{top}/"
    ctx = _PageContext(options=options, tz=tz)
    written: dict[tuple[int, int], str] = {}
    skipped: Counter = Counter()
    pages: list[tuple[int, str, str, int]] = []
    body: list[str] = []
    page_count = 0
    page_players = 0
    page_first_date = page_last_date = ""
    last_day = None
    files = 0

    async def close_page(has_next: bool):
        nonlocal body, page_count, page_players
        number = len(pages) + 1
        pages.append((number, page_first_date, page_last_date, page_count))
        data = render_page(chat, "".join(body), number, has_next).encode("utf-8")
        body = []
        page_count = 0
        page_players = 0
        async for piece in _write_bytes(zf, sink, prefix + _page_file(number), data, zipfile.ZIP_DEFLATED):
            yield piece

    async for msg in messages:
        message_id = int(msg["id"])
        ctx.add_message(message_id)
        plans: list[_MediaPlan] = []
        for n, media in enumerate(msg.get("media") or [], start=1):
            if not isinstance(media, dict):
                continue
            kind = _KIND_OF_TYPE.get(media.get("type"))
            if kind is None:
                continue  # a map picture, a link-preview image: not one of the seven kinds
            stored = media.get("file_name") or os.path.basename(str(media.get("file_path") or ""))
            plan = _MediaPlan(media=media, kind=kind, display_name=media_display_filename(str(stored or "")))
            plans.append(plan)
            if kind not in options.media:
                plan.skip = "not_included"
                continue
            if not media.get("downloaded"):
                plan.skip = "not_downloaded"
                continue
            file_path = media.get("file_path")
            source = await asyncio.to_thread(resolve_media, file_path) if file_path else None
            if source is None:
                plan.skip = "missing"
                continue
            try:
                stat = await asyncio.to_thread(os.stat, source)
            except OSError:
                plan.skip = "missing"
                continue
            plan.size = stat.st_size
            if stat.st_size > options.max_file_bytes:
                plan.skip = "too_large"
                continue
            key = (stat.st_dev, stat.st_ino)
            if key in written:
                plan.entry = written[key]
                plan.duplicate = True
            else:
                plan.entry = media_entry_name(MEDIA_KINDS[kind][1], message_id, n, str(stored or file_path))
                written[key] = plan.entry
            plan.source = source
            plan.player = _player_for(kind, media, options.players)
        players = sum(1 for plan in plans if plan.entry and plan.player in ("video", "audio"))

        # A page ends at MAX_MESSAGES_PER_PAGE messages or before its players pass MAX_PLAYERS_PER_PAGE.
        if page_count and (page_count >= MAX_MESSAGES_PER_PAGE or page_players + players > MAX_PLAYERS_PER_PAGE):
            async for piece in close_page(True):
                yield piece
            last_day = None
        if page_count == 0:
            ctx.page_first_ids.append(message_id)

        for plan in plans:
            if plan.skip:
                skipped[plan.skip] += 1
                continue
            if plan.duplicate:
                plan.poster = poster_of.get(plan.entry)
                continue
            try:
                handle = await asyncio.to_thread(open, plan.source, "rb")
            except OSError:
                # Gone between the check and the copy: drawn as missing, nothing written,
                # and so is every later media of this message that was to share the entry.
                failed = plan.entry
                del written[next(k for k, v in written.items() if v == failed)]
                # The later ones are counted when this loop reaches them.
                for other in plans:
                    if other.entry == failed and not other.skip:
                        other.skip = "missing"
                        other.entry = None
                        other.duplicate = False
                        other.player = None
                skipped["missing"] += 1
                continue
            try:
                size = (await asyncio.to_thread(os.fstat, handle.fileno())).st_size
                with zf.open(_zip_info(prefix + plan.entry, zipfile.ZIP_STORED, size), "w") as dest:
                    while True:
                        chunk = await asyncio.to_thread(handle.read, CHUNK)
                        if not chunk:
                            break
                        dest.write(chunk)
                        if sink.size >= CHUNK:
                            yield sink.take()
            finally:
                handle.close()
            files += 1
            if sink.size >= CHUNK:
                yield sink.take()
            if poster is not None and plan.player == "video" and plan.kind in ("video", "video_note"):
                still = None
                started = time.monotonic()
                try:
                    still = await poster(plan.media, plan.source, poster_seconds < POSTER_BUDGET_SECONDS)
                    data = await asyncio.to_thread(Path(still).read_bytes) if still else None
                except Exception as e:
                    logger.debug(f"Export poster unavailable: {type(e).__name__}")
                    data = None
                poster_seconds += time.monotonic() - started
                if data:
                    plan.poster = f"{plan.entry.rsplit('.', 1)[0] if '.' in plan.entry else plan.entry}_thumb.webp"
                    poster_of[plan.entry] = plan.poster
                    async for piece in _write_bytes(zf, sink, prefix + plan.poster, data, zipfile.ZIP_STORED):
                        yield piece

        ctx.plans = {str(plan.media.get("media_id")): plan for plan in plans}
        when = _parse_date(msg.get("date"))
        if when is not None:
            label = f"{when.astimezone(tz):%d.%m.%Y %H:%M}"
            if page_count == 0:
                page_first_date = label
            page_last_date = label
            day = when.astimezone(tz).date()
            if day != last_day:
                body.append(
                    f'<div class="day_separator"><div class="body details">{_esc(_day_label(when, tz))}</div></div>\n'
                )
                last_day = day
        elif page_count == 0:
            page_first_date = ""
        body.append(render_message(msg, ctx))
        page_count += 1
        page_players += players

    if page_count or not pages:
        async for piece in close_page(False):
            yield piece

    css = _CSS_PATH.read_bytes()
    async for piece in _write_bytes(zf, sink, prefix + "css/style.css", css, zipfile.ZIP_DEFLATED):
        yield piece
    index = render_index(chat, filters, options, pages, skipped, version=version, files=files).encode("utf-8")
    async for piece in _write_bytes(zf, sink, prefix + "index.html", index, zipfile.ZIP_DEFLATED):
        yield piece
    zf.close()
    # The central directory comes out of close() in one go: hand it on in CHUNK pieces.
    tail = sink.take()
    for start in range(0, len(tail), CHUNK):
        yield tail[start : start + CHUNK]
    logger.info(f"HTML export finished: {len(pages)} pages, {files} files, {sum(skipped.values())} skipped")
